//! Embedded web management panel for CandyTunnel.
//!
//! A self-contained HTTP/1.1 server (hand-rolled over `async-net`, no extra web
//! framework) that serves a single-page, bilingual (Persian/English) admin UI
//! and a small JSON API. It manages CandyTunnel instances the same way
//! `candy-manager.sh` does — reading/writing `/etc/candytunnel/*.toml`, driving
//! `systemctl`, tailing `journalctl`, and launching the spoofed-IP tester.
//!
//! Security model:
//!   * Binds `127.0.0.1` by default — expose it only behind SSH/TLS.
//!   * Password login required; 256-bit opaque session tokens in an
//!     HttpOnly, SameSite=Strict cookie.
//!   * Mutating requests must carry an `X-CandyTunnel` header (the SPA sets it),
//!     which together with SameSite=Strict defeats CSRF.
//!   * Login attempts are rate-limited per source IP.
//!   * Instance names are strictly validated; no user input ever reaches a
//!     shell (commands run via argv, never `sh -c`).

